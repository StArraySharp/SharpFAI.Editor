using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;
using SharpFAI.Player.Engine.Filters;

namespace SharpFAI.SourceGenerator;

internal static class FilterAssetDefaultsGenerator
{
    private const string ShaderPrefix = "Resources.Shaders.Filters/";
    private const string TexturePrefix = "Resources.Filters.";
    private const string ShaderSuffix = ".shaderlab";
    private const string MetadataSuffix = ".meta";

    internal static string Generate(string manifest)
    {
        List<string> shaders = new();
        List<string> textures = new();
        List<string> textureAliases = new();
        foreach (string line in manifest.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries))
        {
            string[] parts = line.Split('|');
            if (parts.Length == 3 && parts[0] == "T")
            {
                textureAliases.Add($"[{Quote(parts[1])}] = {Quote(parts[2])},");
                continue;
            }
            if (parts.Length != 4 || parts[0] != "R")
                continue;
            string key = parts[1];
            if (key.StartsWith(ShaderPrefix, StringComparison.Ordinal) && key.EndsWith(ShaderSuffix, StringComparison.Ordinal))
            {
                string name = key.Substring(ShaderPrefix.Length, key.Length - ShaderPrefix.Length - ShaderSuffix.Length);
                var defaults = ShaderLabDefaults.Parse(ReadSource(parts[2]));
                if (defaults.Properties.Count > 0)
                    shaders.Add($"[{Quote(name)}] = new([{string.Join(", ", defaults.Properties.Select(EmitProperty))}]),");
            }
            else if (key.StartsWith(TexturePrefix, StringComparison.Ordinal) && key.EndsWith(MetadataSuffix, StringComparison.Ordinal))
            {
                string filename = key.Substring(TexturePrefix.Length, key.Length - TexturePrefix.Length - MetadataSuffix.Length);
                var sampling = FilterTextureSampling.Parse(ReadSource(parts[2]));
                string mipmaps = sampling.Mipmaps ? "true" : "false";
                textures.Add(FormattableString.Invariant(
                    $"[{Quote(filename)}] = new({mipmaps}, {sampling.FilterMode}, {sampling.WrapU}, {sampling.WrapV}),"));
            }
        }

        return $$"""
            // <auto-generated />
            using System;
            using System.Collections.Generic;
            namespace SharpFAI.Player.Engine.Filters;
            internal static class GeneratedFilterAssetDefaults
            {
                internal static readonly Dictionary<string, ShaderLabDefaults> Shaders = new(StringComparer.Ordinal)
                {
                    {{string.Join("\n        ", shaders)}}
                };
                internal static readonly Dictionary<string, FilterTextureSampling> Textures = new(StringComparer.Ordinal)
                {
                    {{string.Join("\n        ", textures)}}
                };
                internal static readonly Dictionary<string, string> TextureAliases = new(StringComparer.Ordinal)
                {
                    {{string.Join("\n        ", textureAliases)}}
                };
            }
            """;
    }

    private static string EmitProperty(ShaderLabDefaults.Property property)
    {
        string value = property.Type switch
        {
            "Float" or "Range" => $"scalar: {FloatLiteral(property.Scalar)}",
            "Int" or "Integer" => "integer: " + property.Integer.ToString(CultureInfo.InvariantCulture),
            "Vector" or "Color" => $"vector: ({FloatLiteral(property.Vector.X)}, {FloatLiteral(property.Vector.Y)}, " +
                $"{FloatLiteral(property.Vector.Z)}, {FloatLiteral(property.Vector.W)})",
            "2D" => $"texture: {Quote(property.Texture!)}",
            _ => throw new InvalidOperationException("Unsupported ShaderLab property type " + property.Type),
        };
        return $"new({Quote(property.Name)}, {Quote(property.Type)}, {value})";
    }

    private static string FloatLiteral(float value) => value.ToString("R", CultureInfo.InvariantCulture) + "f";
    private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    // Paths and content hashes are supplied by the MSBuild inputs manifest.
#pragma warning disable RS1035
    private static string ReadSource(string path) => File.ReadAllText(path);
#pragma warning restore RS1035
}
